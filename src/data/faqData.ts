/**
 * دالة للبحث في الـ FAQ حسب الكلمات المفتاحية
 */
export const searchFAQ = (query: string): FAQItem[] => {
  const lowerQuery = query.toLowerCase();
  return faqData.filter(faq => 
    faq.keywords.some(keyword => lowerQuery.includes(keyword)) ||
    faq.question.toLowerCase().includes(lowerQuery) ||
    faq.answer.toLowerCase().includes(lowerQuery)
  ).sort((a, b) => a.priority - b.priority);
};

/**
 * دالة للحصول على FAQ حسب الفئة
 */
export const getFAQByCategory = (category: FAQItem['category']): FAQItem[] => {
  return faqData.filter(faq => faq.category === category);
};

/**
 * دالة للحصول على أهم الأسئلة
 */
export const getTopFAQs = (count: number = 5): FAQItem[] => {
  return faqData.sort((a, b) => a.priority - b.priority).slice(0, count);
};
